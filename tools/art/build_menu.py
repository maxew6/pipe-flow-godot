"""Builds the layered main-menu scenery into assets/menu/ and writes
scripts/ui/menu_art_layout.gd (positions of every layer in the 1200x2400 art space)."""
import os, json
import numpy as np
from PIL import Image
from common import *
import scene_a as A
import scene_b as B

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'assets', 'menu')
W, H = A.W, A.H
PALS = [((28, 92, 44), (56, 142, 60), (130, 204, 84)),
        ((22, 104, 70), (40, 160, 92), (120, 222, 130)),
        ((46, 110, 40), (96, 166, 56), (170, 220, 90))]
layout = {}


def new():
    return Image.new('RGBA', (W, H), (0, 0, 0, 0))


def save_cropped(name, img, pad=0):
    bbox = img.getbbox()
    if bbox is None:
        return None
    x0, y0, x1, y1 = max(0, bbox[0] - pad), max(0, bbox[1] - pad), min(W, bbox[2] + pad), min(H, bbox[3] + pad)
    crop = img.crop((x0, y0, x1, y1))
    crop.save(os.path.join(OUT, name + '.png'), optimize=True)
    layout[name] = (x0, y0, x1 - x0, y1 - y0)
    return crop


def fg_leaf_layers():
    bl = new()
    B.rosette(bl, (110, 2440), 12, 380, 540, 120, 170, 18, 150, 101, PALS)
    B.rosette(bl, (-30, 2330), 7, 260, 380, 90, 130, -12, 70, 131, PALS)
    br = new()
    B.rosette(br, (1210, 2440), 10, 320, 460, 100, 140, 105, 172, 151, PALS)
    tl = new()
    # branch/trunk
    import PIL.ImageDraw as D
    big = Image.new('RGBA', (W * SS, H * SS), (0, 0, 0, 0))
    d = D.Draw(big)
    trunk = [(-20, 590), (-20, 470), (60, 410), (130, 320), (176, 250), (202, 262), (172, 350), (120, 460), (70, 555)]
    d.polygon([(x * SS, y * SS) for x, y in trunk], fill=hexc('5a3a1c'))
    d.line([(60 * SS, 560 * SS), (130 * SS, 380 * SS), (176 * SS, 270 * SS)], fill=hexc('8a5a30'), width=5 * SS)
    tl.alpha_composite(down(big))
    for (bx, by, a0, a1, s) in [(150, 300, -20, 200, 201), (80, 450, 10, 150, 211), (190, 150, 0, 200, 221), (60, 130, 10, 190, 231), (250, 260, -40, 120, 241)]:
        B.rosette(tl, (bx, by), 8, 170, 260, 70, 104, a0, a1, s, PALS)
    return bl, br, tl


def tiles():
    # vertical water streaks (tileable in y) for the waterfall overlay
    th, tw = 512, 128
    n = ndi.gaussian_filter(np.random.default_rng(5).random((th, tw)).astype(np.float32), (14, 1.4), mode='wrap')
    n = (n - n.min()) / (n.max() - n.min())
    a = smoothstep(0.55, 0.85, n) * 0.85
    Image.fromarray(np.dstack([np.full((th, tw, 3), 255, np.uint8), (a * 255).astype(np.uint8)]), 'RGBA').save(os.path.join(OUT, 'fall_streaks.png'), optimize=True)
    # horizontal river glints (tileable in x)
    th, tw = 256, 512
    n = ndi.gaussian_filter(np.random.default_rng(6).random((th, tw)).astype(np.float32), (2.2, 22), mode='wrap')
    n = (n - n.min()) / (n.max() - n.min())
    a = smoothstep(0.62, 0.9, n) * 0.55
    Image.fromarray(np.dstack([np.full((th, tw, 3), 255, np.uint8), (a * 255).astype(np.uint8)]), 'RGBA').save(os.path.join(OUT, 'river_glints.png'), optimize=True)


def main():
    os.makedirs(OUT, exist_ok=True)
    sky = A.build_sky()
    sky.convert('RGB').save(os.path.join(OUT, 'sky.png'), optimize=True)
    layout['sky'] = (0, 0, W, H)
    cl = [(40, 380, 560, 290, 1), (640, 250, 480, 250, 2), (110, 860, 600, 300, 3), (760, 1060, 420, 210, 4)]
    for i, (x, y, w, h, s) in enumerate(cl, 1):
        img = B_cloud = A.cloud(w, h, s)
        c = new(); blit(c, img, x, y)
        save_cropped('cloud_%d' % i, c)
    save_cropped('mountains', A.build_mountains())
    mid = A.build_midground()
    blit(mid, B.build_house(), 905, 1545)
    save_cropped('midground', mid)
    save_cropped('river', B.build_river())

    sc = new()
    blit(sc, B.cliff(430, 560, 3), 0, 1340)
    blit(sc, B.waterfall(112, 455, 4), 156, 1402)
    B.foam_and_mist(sc, 214, 1862, 150)
    blit(sc, B.tower(), 45, 920)
    for (x, y, w, h, s) in [(10, 1790, 150, 110, 61), (270, 1810, 130, 96, 62), (350, 1760, 90, 66, 63), (-20, 1870, 120, 90, 64)]:
        blit(sc, B.rock(w, h, s), x, y)
    # right bank
    for (x, y, w, h, s) in [(880, 1860, 220, 160, 71), (1040, 1840, 190, 140, 72), (800, 2010, 130, 96, 73), (1050, 2060, 170, 120, 74)]:
        blit(sc, B.rock(w, h, s), x, y)
    bush_pal = ((30, 96, 48), (62, 146, 60), (130, 204, 84))
    blit(sc, A.canopy(240, 170, 81, bush_pal, n=12, flat_bottom=True), 950, 1735)
    blit(sc, A.canopy(190, 140, 82, ((22, 104, 70), (40, 158, 92), (120, 214, 128)), n=10, flat_bottom=True), 860, 1790)
    save_cropped('scenery', sc)

    bl, br, tl = fg_leaf_layers()
    save_cropped('fg_bl', bl)
    save_cropped('fg_br', br)
    save_cropped('fg_tl', tl)
    tiles()

    # layout constants for Godot
    lines = ['# GENERATED by tools/art/build_menu.py - do not edit by hand.',
             '# Position/size of every menu layer inside the 1200x2400 art space.',
             'class_name MenuArtLayout',
             'extends RefCounted', '',
             'const ART_SIZE := Vector2(1200.0, 2400.0)',
             '## Region guaranteed visible on every supported portrait aspect (9:16 to 9:20).',
             'const SAFE_RECT := Rect2(60.0, 133.0, 1080.0, 2134.0)',
             'const WATERFALL_RECT := Rect2(176.0, 1420.0, 70.0, 400.0)',
             'const RIVER_RECT := Rect2(0.0, 1760.0, 1200.0, 640.0)',
             'const LAYERS := {']
    for k, (x, y, w, h) in layout.items():
        lines.append('\t"%s": Rect2(%d.0, %d.0, %d.0, %d.0),' % (k, x, y, w, h))
    lines.append('}')
    open(os.path.join(ROOT, 'scripts', 'ui', 'menu_art_layout.gd'), 'w').write('\n'.join(lines) + '\n')
    print('layers:', {k: v for k, v in layout.items()})


if __name__ == '__main__':
    main()
